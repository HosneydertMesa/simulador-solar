export function panelById(id: string): PanelSpec {
  return PANELS.find((p) => p.id === id) ?? PANELS[0];
}
export function inverterById(id: string): InverterSpec {
  return INVERTERS.find((i) => i.id === id) ?? INVERTERS[0];
}
export function batteryById(id: string): BatterySpec {
  return BATTERIES.find((b) => b.id === id) ?? BATTERIES[0];
}
export function supplierById(id: string): Supplier {
  return SUPPLIERS.find((s) => s.id === id) ?? SUPPLIERS[0];
}

function wantPortable(topology: Topology): boolean {
  return topology === "portable";
}

export function panelsFor(topology: Topology): PanelSpec[] {
  const portable = wantPortable(topology);
  return PANELS.filter((p) => (formFactorOf(p) === "portable") === portable);
}
export function invertersFor(topology: Topology): InverterSpec[] {
  const portable = wantPortable(topology);
  return INVERTERS.filter((i) => (formFactorOf(i) === "portable") === portable);
}
export function batteriesFor(topology: Topology): BatterySpec[] {
  const portable = wantPortable(topology);
  return BATTERIES.filter((b) => (formFactorOf(b) === "portable") === portable);
}
